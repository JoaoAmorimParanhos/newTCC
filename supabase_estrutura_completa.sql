-- ---------------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------------

-- Tipos de sala (Sala de aula, Laboratório, Quadra...).
create table public.tb_tipo_sala (
  id bigint generated by default as identity not null,
  nome text not null
);

-- Salas: tipo + número (ex.: Laboratório de informática 1).
create table public.tb_sala (
  id serial not null,
  numero integer not null,
  id_tipo_sala bigint not null
);

-- Componentes curriculares (no código: "matéria").
create table public.tb_materia (
  id serial not null,
  nome character varying(100) not null
);

create table public.tb_professor (
  id serial not null,
  nome character varying(100) not null
);

-- Quais componentes cada professor pode dar.
create table public.tb_professor_materia (
  id_professor integer not null,
  id_materia integer not null
);

-- Horários em que o professor não pode dar aula (tela Disponibilidade).
-- dia_semana: 1 = segunda ... 5 = sexta; periodo: 1 a 16
-- (1–6 manhã, 7–12 tarde, 13–16 noite).
create table public.tb_professor_indisponibilidade (
  id bigint generated always as identity not null,
  id_professor bigint not null,
  dia_semana integer not null,
  periodo integer not null
);

-- Cursos (turmas) e o turno em que o gerador coloca as aulas.
create table public.tb_curso (
  id serial not null,
  nome character varying(100) not null,
  id_sala integer,
  periodo_preferencia text default 'manha_tarde'::text not null
);

-- Carga do curso: aulas por semana e tamanho do bloco de cada componente.
create table public.tb_curso_materia (
  id_curso integer not null,
  id_materia integer not null,
  quantidade_aulas integer default 1 not null,
  tamanho_bloco integer default 1 not null
);

-- Aulas divididas (turma em 2 grupos ao mesmo tempo).
create table public.tb_curso_aula_geminada (
  id bigint generated by default as identity not null,
  id_curso bigint not null,
  id_materia_a bigint not null,
  id_materia_b bigint not null,
  created_at timestamp with time zone default now() not null,
  quantidade_periodos integer default 1 not null,
  quantidade_blocos integer default 1 not null,
  quantidade_periodos_b integer not null
);

-- Grade horária: cada linha é uma aula de um grupo num horário.
create table public.tb_aula (
  id bigint generated always as identity not null,
  id_curso bigint not null,
  dia_semana integer not null,
  periodo integer not null,
  id_materia bigint not null,
  id_professor bigint not null,
  id_sala bigint,
  grupo integer default 1 not null
);

-- Texto do horário de cada período (ex.: "07:15 - 08:05").
create table public.tb_horario_periodo (
  periodo integer not null,
  texto text default ''::text not null
);

