-- Rode no SQL Editor do Supabase (uma vez), depois de supabase_aulas_geminadas.sql.
-- 1) 4 períodos à noite  2) turma noturna  3) horário (texto) de cada período
-- 4) tipos de sala cadastráveis (com Quadra)  5) geminada com cargas diferentes

begin;

-- 1) Noite: períodos 13–16 ----------------------------------------------------
alter table public.tb_aula drop constraint if exists tb_aula_periodo_check;
alter table public.tb_aula
  add constraint tb_aula_periodo_check check (periodo between 1 and 16);

alter table public.tb_professor_indisponibilidade
  drop constraint if exists tb_professor_indisponibilidade_periodo_check;
alter table public.tb_professor_indisponibilidade
  add constraint tb_professor_indisponibilidade_periodo_check
  check (periodo between 1 and 16);

-- 2) Turma noturna --------------------------------------------------------------
alter table public.tb_curso drop constraint if exists tb_curso_periodo_preferencia_check;
alter table public.tb_curso
  add constraint tb_curso_periodo_preferencia_check
  check (periodo_preferencia in ('manha_tarde', 'tarde_manha', 'noite'));

-- 3) Horário de cada período (texto livre, vale para todas as turmas) ----------
create table if not exists public.tb_horario_periodo (
  periodo int primary key check (periodo between 1 and 16),
  texto text not null default ''
);
alter table public.tb_horario_periodo enable row level security;
drop policy if exists anon_all_tb_horario_periodo on public.tb_horario_periodo;
create policy anon_all_tb_horario_periodo on public.tb_horario_periodo
  for all to anon using (true) with check (true);

-- 4) Tipos de sala ------------------------------------------------------------
create table if not exists public.tb_tipo_sala (
  id bigint generated by default as identity primary key,
  nome text not null unique
);
alter table public.tb_tipo_sala enable row level security;
drop policy if exists anon_all_tb_tipo_sala on public.tb_tipo_sala;
create policy anon_all_tb_tipo_sala on public.tb_tipo_sala
  for all to anon using (true) with check (true);

insert into public.tb_tipo_sala (nome) values
  ('Sala de aula'),
  ('Laboratório de informática'),
  ('Quadra')
on conflict (nome) do nothing;

alter table public.tb_sala
  add column if not exists id_tipo_sala bigint references public.tb_tipo_sala(id);

update public.tb_sala s
set id_tipo_sala = t.id
from public.tb_tipo_sala t
where s.id_tipo_sala is null
  and t.nome = case s.tipo::text
    when 'laboratorio_informatica' then 'Laboratório de informática'
    else 'Sala de aula'
  end;

alter table public.tb_sala alter column id_tipo_sala set not null;
alter table public.tb_sala drop constraint if exists tb_sala_tipo_numero_unica;
alter table public.tb_sala
  add constraint tb_sala_tipo_numero_unica unique (id_tipo_sala, numero);
alter table public.tb_sala drop column if exists tipo;
-- O enum antigo (sala_aula / laboratorio_informatica) não é mais usado.
drop type if exists public.tipo_sala;

-- 5) Geminada com cargas diferentes ---------------------------------------------
-- quantidade_periodos = aulas da matéria A; quantidade_periodos_b = da matéria B.
alter table public.tb_curso_aula_geminada
  add column if not exists quantidade_periodos_b int;
update public.tb_curso_aula_geminada
set quantidade_periodos_b = quantidade_periodos
where quantidade_periodos_b is null;
alter table public.tb_curso_aula_geminada
  alter column quantidade_periodos_b set not null;

alter table public.tb_curso_aula_geminada
  drop constraint if exists tb_curso_aula_geminada_periodos_b_positivos;
alter table public.tb_curso_aula_geminada
  add constraint tb_curso_aula_geminada_periodos_b_positivos
  check (quantidade_periodos_b >= 1);

alter table public.tb_curso_aula_geminada
  drop constraint if exists tb_curso_aula_geminada_blocos_validos;
alter table public.tb_curso_aula_geminada
  add constraint tb_curso_aula_geminada_blocos_validos
  check (
    quantidade_blocos >= 1
    and quantidade_blocos <= greatest(quantidade_periodos, quantidade_periodos_b)
  );

commit;
